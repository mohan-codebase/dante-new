                                            <h3 style="margin-top:30px;">What is TMJ Disorder?</h3>
                                            <p>TMJ disorder, or temporomandibular joint disorder, affects the jaw joint and surrounding muscles. It occurs when the jaw joint is overused, inflamed, or injured. Located near the ear, the TMJ helps with talking, chewing, and swallowing. When it becomes inflamed or irritated, it can cause jaw pain and radiating symptoms to nearby areas, including the ear canal.</p>
                                            <p>Common causes include teeth grinding, jaw clenching, trauma, and arthritis. TMJ-related pain often overlaps with ear problems, making diagnosis harder. People may not notice the connection until they experience persistent ear pain, jaw discomfort, or dizziness. Treatment helps reduce pain and restore normal jaw function.</p>
