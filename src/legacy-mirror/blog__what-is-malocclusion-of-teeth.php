                </div>

                <div id="faqFour" class="collapse" data-parent="#faqAccordionMalocclusion">
                    <div class="card-body">
                    Some severe skeletal cases need jaw surgery or orthognathic surgery because tooth movement alone cannot fix jaw imbalance. Surgery repositions jaw bones, then braces or aligners fine-tune the bite. Your orthodontist and surgeon plan it together.
                    </div>
                </div>
