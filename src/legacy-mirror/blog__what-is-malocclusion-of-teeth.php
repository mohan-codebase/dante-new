                    1. Can baby teeth cause bite problems later?
                    </button>
                </div>

                <div id="faqOne" class="collapse" data-parent="#faqAccordionMalocclusion">
                    <div class="card-body">
                    Yes. The child’s baby teeth guide where the permanent teeth erupt. Early tooth loss, crowding, or habits can shift developing teeth. So, a minor issue in baby teeth can grow into a larger alignment problem later.
                    </div>
                </div>
                </div>

                <!-- Item 2 -->
                <div class="card">
                <div class="card-header p-0">
                    <button class="faq-btn full-click" data-toggle="collapse" data-target="#faqTwo">
                    2. Does mouth breathing affect teeth and gums?
                    </button>
                </div>

                <div id="faqTwo" class="collapse" data-parent="#faqAccordionMalocclusion">
                    <div class="card-body">
                    Yes. Mouth breathing dries oral tissues and can irritate gums. Also, it often links with poor tongue posture and narrow arches. Over time, that can support crowding and bite changes, plus higher gum inflammation risk.
                    </div>
                </div>
                </div>

                <!-- Item 3 -->
                <div class="card">
                <div class="card-header p-0">
                    <button class="faq-btn full-click" data-toggle="collapse" data-target="#faqThree">
