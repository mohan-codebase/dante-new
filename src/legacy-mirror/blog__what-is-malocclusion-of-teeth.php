                    </button>
                </div>

                <div id="faqThree" class="collapse" data-parent="#faqAccordionMalocclusion">
                    <div class="card-body">
                    Braces often work best for severe crowding, rotations, and complex bite shifts. They give strong control for moving teeth and closing gaps. Aligners fit mild to moderate cases. Your exam decides what fits your bite.
                    </div>
                </div>
                </div>

                <!-- Item 4 -->
