        const updateSlider = (slider, event) => {
            const rect = slider.getBoundingClientRect();
            let x = event.clientX - rect.left; // x position within the element.

            if (event.touches) {
                x = event.touches[0].clientX - rect.left; // For touch events on mobile devices
            }

            if (x < 0) x = 0;
            if (x > rect.width) x = rect.width;

            const percentage = (x / rect.width) * 100;

            // Adjust clip-path for both images based on mouse position
            const clipAfter = `polygon(0% 0%, ${percentage}% 0%, ${percentage}% 100%, 0% 100%)`;
            const clipBefore = `polygon(${percentage}% 0%, 100% 0%, 100% 100%, ${percentage}% 100%)`;

            slider.querySelector('.after').style.clipPath = clipAfter;
            slider.querySelector('.before').style.clipPath = clipBefore;

            // Move slider overlay smoothly
            slider.querySelector('.slider-overlay').style.left = `${percentage}%`;
        };

        // Add event listeners for each slider
        const sliders = document.querySelectorAll('.slider');
        sliders.forEach(slider => {
            slider.addEventListener('mousemove', (event) => updateSlider(slider, event));
            slider.addEventListener('click', (event) => updateSlider(slider, event));
            slider.addEventListener('touchmove', (event) => updateSlider(slider, event));
            slider.addEventListener('touchstart', (event) => updateSlider(slider, event));
        });
    </script>
