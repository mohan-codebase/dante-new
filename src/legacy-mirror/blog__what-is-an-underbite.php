                                    <div class="col-md-8">
                                        <div class="info">
                                            <h3 style="margin-top:30px;">What Is an Underbite and Why Does It Happen?</h3>
                                            <p>An underbite is when the lower jaw extends forward, causing the bottom teeth to sit ahead of the top teeth. While a slight underbite might not pose a major issue, a more severe case can lead to serious problems over time.</p>
                                            <p>The main reasons for underbites are genetic factors, habits, and even developmental issues during childhood. For example, if one or both parents had an underbite, it’s likely for a child to inherit this jaw structure. Certain childhood habits, like prolonged thumb sucking, tongue thrusting, or excessive pacifier use, can also lead to an underbite. In other cases, a child’s jaw may not develop properly, causing the lower jaw to extend outwards.</p>
