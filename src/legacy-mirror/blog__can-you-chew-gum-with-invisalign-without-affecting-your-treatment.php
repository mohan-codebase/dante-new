                                        <div class="info">
                                            <p>Patients love Invisalign for being low-profile, but aligners still require careful handling. Removing trays for anything besides water helps prevent staining, warping, and tooth decay. Even one slip-up, like chewing gum, can affect the fit of your trays. That means more time wearing them and potential costs for replacements. Orthodontists stress consistency, wear aligners regularly, keep them properly cleaned, and avoid habits like chewing gum that risk your oral health.</p>
                                            <h3 style="margin-top:30px;">What to Do If You Accidentally Chewed Gum with Invisalign </h3>
                                            <p>Accidentally chewing gum with Invisalign in happens more often than you might think. If you act quickly, you can limit damage to your trays and teeth.</p>
                                            <p class="mt-4"><b>Step 1: Remove Aligners Immediately</b></p>
                                            <p>Stop chewing right away and remove your aligners. Gum can stick more if left too long. Check for damage like bends or cracks. If you have a backup tray from your previous set, keep it just in case.</p>

                                            <p class="mt-4"><b>Step 2: Clean the Aligners Thoroughly</b></p>
                                            <p>Rinse with lukewarm water. Avoid hot water, it warps the plastic. Use a soft toothbrush and Invisalign-safe cleanser to scrub off residue. Do not use toothpaste or soap that may scratch or stain.</p>

                                            <p class="mt-4"><b>Step 3: Brush and Rinse Your Mouth</b></p>
                                            <p>Brush to get rid of sugar and food particles left from the gum. Rinse with plain or sparkling water before putting trays back in. This prevents tooth decay and helps maintain your oral health.</p>

                                            <p class="mt-4"><b>Step 4: Check the Fit</b></p>
                                            <p>Once clean, put the trays back in. If they feel loose or don’t fit well, they might be warped. In that case, call your orthodontist. A poor fit could slow down your progress or require new trays.</p>
