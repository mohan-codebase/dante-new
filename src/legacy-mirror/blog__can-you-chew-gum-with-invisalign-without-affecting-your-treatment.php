                                              </div>
                                              <div class="col-md-6">
                                                  <div class="info">
                                                      
                                                      <p><b>Orthodontist Recommendations:</b></p>
                                                      <ul class="ul" style="list-style-type:disc;">
                                                        <li>Always remove trays before eating or chewing</li>
                                                        <li>Avoid sticky and sugary gum completely</li>
                                                        <li>Don’t chew sugar-free gum with trays in</li>
                                                        <li>Brush and rinse before putting trays back in</li>
                                                      </ul>
                                                      <p><b>Why They Recommend This:</b></p>
                                                      <ul class="ul" style="list-style-type:disc;">
                                                        <li>Gum can weaken or deform aligners, reducing their effectiveness.</li>
                                                        <li>It encourages plaque buildup by trapping sugar against your teeth.</li>
                                                        <li>Gum residue can make trays cloudy or smelly.</li>
                                                        <li>Chewing may cause trays to lose their snug fit, delaying progress.</li>
                                                      </ul>
                                                      <p>Extra Care Tips:</p>
                                                      <ul class="ul" style="list-style-type:disc;">
                                                        <li>Drink only plain or sparkling water while wearing aligners.</li>
                                                        <li>Never drink hot coffee with Invisalign, as it can melt or warp the plastic.</li>
                                                        <li>Rinse your mouth after beverages like tea, fruit juices, or sugary drinks.</li>
                                                      </ul>
