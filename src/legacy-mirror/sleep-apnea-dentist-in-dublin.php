<script>
  document.addEventListener("DOMContentLoaded", function () {
    // Handle submenu click toggle
    document.querySelectorAll('.dropdown-submenu > a').forEach(function (element) {
      element.addEventListener("click", function (e) {
        e.preventDefault();
        e.stopPropagation();

        // Safely find parent menu (may be null for top-level items)
        const parentMenu = this.closest('.dropdown-menu');

        // Close other open submenus only if parent menu exists
        if (parentMenu) {
          parentMenu.querySelectorAll('.dropdown-menu.show').forEach(function (submenu) {
            if (submenu !== element.nextElementSibling) submenu.classList.remove('show');
          });
        }

        // Toggle this submenu
        const submenu = this.nextElementSibling;
        if (submenu) submenu.classList.toggle('show');
      });
    });

    // Close submenus when clicking outside any dropdown
    document.addEventListener("click", function () {
      document.querySelectorAll('.dropdown-submenu .dropdown-menu.show').forEach(function (submenu) {
        submenu.classList.remove('show');
      });
    });
  });
</script>

